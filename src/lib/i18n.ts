/** Textos para un idioma ('es_MX', 'es', 'en_US'...). Todo lo que no es español va en inglés. */
export function textos(idioma: string): Textos {
  return idioma.toLowerCase().startsWith('es') ? es : en;
}

/** Idioma efectivo: el elegido en Ajustes o, en automático, el del cliente del LoL. */
export function idiomaEfectivo(elegido: string, cliente: string): string {
  return elegido === 'auto' ? cliente || navigator.language : elegido;
}

/** Color de la escala de tiers del tema (0 = el mejor … 4 = el peor). */
const tierColor = (i: number) => `var(--tier-${Math.min(4, Math.max(0, i))})`;

/** (palabra, color, letra) de un tier de aumento de OP.GG (0 = S … 6 = F). */
export function calidad(T: Textos, tier: number | null): [string, string, string] {
  if (tier === null) return [T.sin_datos, tierColor(4), '?'];
  if (tier < T.tiers.length) return [T.tiers[tier], tierColor(tier), 'SABCDEF'[tier]];
  return [T.mala, tierColor(4), 'SABCDEF'[tier]];
}

/** Etiqueta y color del tier de un campeón en ARAM: Caos (1 = mejor … 5). */
export function tierCampeon(tier: number | null): [string, string] {
  return tier ? [`T${tier}`, tierColor(tier - 1)] : ['—', tierColor(4)];
}
